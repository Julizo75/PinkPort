-- =============================================
-- PinkPort - Tablas de la base de datos
-- Pegar en: Supabase > SQL Editor > New query > Run
-- =============================================

-- 1. Usuarios
create table usuario (
  id_usuario integer generated by default as identity primary key,
  nombre text not null,
  correo text not null unique,
  contrasena text not null,
  telefono text,
  ciudad text,
  direccion text,
  rol text not null default 'cliente',
  fecha_registro date default current_date
);

-- 2. Categorías
create table categoria (
  id_categoria integer generated by default as identity primary key,
  nombre text not null,
  descripcion text
);

-- 3. Productos
create table producto (
  id_producto integer generated by default as identity primary key,
  id_categoria integer references categoria(id_categoria),
  nombre text not null,
  marca text,
  precio numeric not null,
  stock integer default 0,
  imagen_url text
);

-- 4. Pedidos
create table pedido (
  id_pedido integer generated by default as identity primary key,
  id_usuario integer references usuario(id_usuario),
  fecha_pedido timestamp default now(),
  direccion_envio text not null,
  subtotal numeric,
  costo_envio numeric,
  iva numeric,
  total numeric not null,
  estado text default 'pendiente'
);

-- 5. Detalle del pedido
create table detalle_pedido (
  id_detalle integer generated by default as identity primary key,
  id_pedido integer references pedido(id_pedido),
  id_producto integer references producto(id_producto),
  cantidad integer not null,
  precio_unitario numeric not null
);

-- Seguridad: nadie puede entrar a las tablas desde el navegador.
-- Solo nuestro servidor (backend), que usa la clave secreta.
alter table usuario enable row level security;
alter table categoria enable row level security;
alter table producto enable row level security;
alter table pedido enable row level security;
alter table detalle_pedido enable row level security;

-- Permiso para la clave secreta (service_role)
grant all on all tables in schema public to service_role;
grant all on all sequences in schema public to service_role;
